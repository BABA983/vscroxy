// Command build bundles the Postman sandbox libraries vscroxy embeds.
//
// Run it through ../build.sh, which installs the exact npm inputs from
// package-lock.json first. It writes the bundles to internal/request/js/vendor
// and records their SHA-256 in build/hashes.txt.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json/v2"
	"fmt"
	"os"
	"path/filepath"
	"runtime/debug"
	"slices"
	"strings"

	"github.com/evanw/esbuild/pkg/api"
)

// entry is one generated module. spec is what the bundle's entry file
// requires; name is the path under js/vendor without ".js".
type entry struct {
	name, spec string
}

var entries = []entry{
	{"cheerio", "cheerio"},
	{"xml2js", "xml2js"},
	{"csv-parse-sync", "csv-parse/lib/sync"},
	{"tv4", "tv4"},
	{"uuid", "uuid"},
	{"postman-collection", "postman-collection"},
	{"liquid-json", "liquid-json"},
	{"backbone", "backbone"},
	{"node/assert", "assert"},
	{"node/buffer", "buffer"},
	{"node/events", "events"},
	{"node/fs", "fs"},
	{"node/os", "os-browserify"},
	{"node/path", "path-browserify"},
	{"node/process", "process"},
	{"node/punycode", "punycode"},
	{"node/querystring", "querystring-es3"},
	{"node/stream", "stream-browserify"},
	{"node/string_decoder", "string_decoder"},
	{"node/timers", "timers"},
	{"node/url", "url"},
	{"node/util", "util"},
}

// builtin maps a Node builtin name to the browserify package Postman's
// sandbox uses for it. fs and timers are local shims.
var builtin = map[string]string{
	"assert":         "assert",
	"buffer":         "buffer",
	"events":         "events",
	"fs":             "",
	"os":             "os-browserify",
	"path":           "path-browserify",
	"process":        "process",
	"_process":       "process",
	"punycode":       "punycode",
	"querystring":    "querystring-es3",
	"stream":         "stream-browserify",
	"string_decoder": "string_decoder",
	"timers":         "",
	"url":            "url",
	"util":           "util",
}

func main() {
	root, err := os.Getwd()
	check(err)
	tmp, err := os.MkdirTemp("", "vscroxy-sandbox-")
	check(err)
	defer os.RemoveAll(tmp)

	shims := map[string]string{}
	for name, pkg := range builtin {
		var source string
		switch name {
		case "fs":
			source = mustRead(filepath.Join(root, "shims", "empty.js"))
		case "timers":
			source = mustRead(filepath.Join(root, "shims", "timers.js"))
		default:
			source = "module.exports = require(" + quote(filepath.Join(root, "node_modules", pkg)) + ");\n"
		}
		path := filepath.Join(tmp, "shim-"+name+".js")
		check(os.WriteFile(path, []byte(source), 0o644))
		shims[name] = path
	}

	plugin := api.Plugin{Name: "postman-node-shims", Setup: func(build api.PluginBuild) {
		names := make([]string, 0, len(shims))
		for name := range shims {
			names = append(names, name)
		}
		slices.Sort(names)
		filter := "^(" + strings.Join(names, "|") + ")$"
		build.OnResolve(api.OnResolveOptions{Filter: filter}, func(args api.OnResolveArgs) (api.OnResolveResult, error) {
			return api.OnResolveResult{Path: shims[args.Path]}, nil
		})
	}}

	hashes := map[string]string{}
	for _, e := range entries {
		source := "module.exports = require(" + quote(e.spec) + ");\n"
		result := api.Build(api.BuildOptions{
			Stdin:            &api.StdinOptions{Contents: source, ResolveDir: root, Sourcefile: e.name + ".entry.js", Loader: api.LoaderJS},
			Bundle:           true,
			Format:           api.FormatCommonJS,
			Platform:         api.PlatformBrowser,
			Target:           api.ES2017,
			MinifyWhitespace: true,
			MinifySyntax:     true,
			LegalComments:    api.LegalCommentsNone,
			Write:            false,
			LogLevel:         api.LogLevelSilent,
			Outfile:          e.name + ".js",
			Plugins:          []api.Plugin{plugin},
		})
		if len(result.Errors) > 0 {
			for _, problem := range result.Errors {
				fmt.Fprintln(os.Stderr, problem.Text)
			}
			os.Exit(1)
		}
		out := filepath.Join("..", "vendor", filepath.FromSlash(e.name)+".js")
		check(os.MkdirAll(filepath.Dir(out), 0o755))
		check(os.WriteFile(out, result.OutputFiles[0].Contents, 0o644))
		hashes[e.name] = digest(result.OutputFiles[0].Contents)
	}
	lines := []string{"# Generated by build.sh from package-lock.json; do not edit.", ""}
	names := mapsKeys(hashes)
	slices.Sort(names)
	for _, name := range names {
		lines = append(lines, hashes[name]+"  "+name+".js")
	}
	check(os.WriteFile("hashes.txt", []byte(strings.Join(lines, "\n")+"\n"), 0o644))

	var lock struct {
		Packages map[string]struct {
			Version   string `json:"version"`
			Resolved  string `json:"resolved"`
			Integrity string `json:"integrity"`
		} `json:"packages"`
	}
	check(json.Unmarshal(mustReadBytes("package-lock.json"), &lock))
	sources := []string{"# Generated by build.sh from package-lock.json; do not edit.", ""}
	for key, pkg := range lock.Packages {
		if !strings.HasPrefix(key, "node_modules/") || strings.Contains(strings.TrimPrefix(key, "node_modules/"), "/") {
			continue
		}
		sources = append(sources, fmt.Sprintf("%s %s %s %s", strings.TrimPrefix(key, "node_modules/"), pkg.Version, pkg.Resolved, pkg.Integrity))
	}
	slices.Sort(sources[2:])
	check(os.WriteFile("sources.txt", []byte(strings.Join(sources, "\n")+"\n"), 0o644))

	version := "unknown"
	if info, ok := debug.ReadBuildInfo(); ok {
		for _, dep := range info.Deps {
			if dep.Path == "github.com/evanw/esbuild" {
				version = dep.Version
			}
		}
	}
	fmt.Printf("wrote %d bundles with esbuild %s\n", len(entries), version)
}

func quote(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func mustRead(path string) string { return string(mustReadBytes(path)) }

func mustReadBytes(path string) []byte {
	b, err := os.ReadFile(path)
	check(err)
	return b
}

func digest(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

func check(err error) {
	if err != nil {
		panic(err)
	}
}

func mapsKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	return keys
}
