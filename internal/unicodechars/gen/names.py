#!/usr/bin/env python3
"""Regenerate names_generated.go from the flagged code points in data_generated.go.

go generate ./internal/unicodechars runs this after `go run ./gen`; python3 and
gofmt must be on PATH. Only code points VS Code flags get a name entry.
"""

import pathlib
import re
import subprocess
import sys
import unicodedata

package = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(".")
source = (package / "data_generated.go").read_text()
points = set()

invisible = source.split("var invisibleRanges", 1)[1].split("// Confusable", 1)[0]
for first, last in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", invisible):
    points.update(range(int(first, 16), int(last, 16) + 1))

for first, _primary in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", source.split("var ambiguousData", 1)[1]):
    points.add(int(first, 16))

names = {}
for code_point in points:
    try:
        names[code_point] = unicodedata.name(chr(code_point))
    except ValueError:
        pass

lines = [
    "// Code generated by go generate ./internal/unicodechars; DO NOT EDIT.",
    f"// Character names from Unicode {unicodedata.unidata_version} (Python unicodedata),",
    "// for the code points VS Code flags. Regenerate both generated files from the",
    "// repository root with: go generate ./internal/unicodechars",
    "",
    "package unicodechars",
    "",
    "// CodePointName is the Unicode name of a flagged code point, or empty when",
    "// the Unicode database gives it none. It is data, not a translatable UI string.",
    "func CodePointName(codePoint rune) string {",
    "\treturn codePointNames[codePoint]",
    "}",
    "",
    "var codePointNames = map[rune]string{",
]
for code_point in sorted(names):
    lines.append(f'\t0x{code_point:04X}: "{names[code_point]}",')
lines.append("}")

output = package / "names_generated.go"
output.write_text("\n".join(lines) + "\n")
subprocess.run(["gofmt", "-w", str(output)], check=True)
