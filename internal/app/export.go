// These options describe fields, not guesses about which strings are secrets.
// The zero value deliberately leaves every field intact.
type exportOptions struct {
	Headers, Query, Auth, Variables bool
	Bodies, ScriptsNotes            bool
}

func safeExportOptions() exportOptions {
	return exportOptions{Headers: true, Query: true, Auth: true, Variables: true, Bodies: true, ScriptsNotes: true}
}

type exportReview struct {
	open, unredacted, reviewed bool
	title, file                string
	data                       []byte
	warnings                   []string
	options                    exportOptions
}

// reviewExport is called on the UI thread, with already-marshaled bytes. It
// owns a copy; changing options or exporting never edits the source document.
func (a *app) reviewExport(title, file string, data []byte, warnings []string) {
	a.exportUI = exportReview{open: true, title: title, file: file, data: bytes.Clone(data),
		warnings: slices.Clone(warnings), options: safeExportOptions()}
}

func (a *app) exportModal(c *ui.Context, t *ui.Theme) {
	s := &a.exportUI
	if !s.open {
		return
	}
	c.CloseToast("")
	uikit.Modal(c, &s.open, func() {
		uikit.DialogColumn(c, uikit.DialogMedium).Children(func() {
			uikit.DialogTitle(c, s.title)
			ui.Scroll(c).MinHeight(0).Shrink(1).Gap(t.Space(2)).Children(func() {
				uikit.Hint(c, "Redact the exported copy. Your saved originals stay unchanged.")
				before, raw := s.options, s.unredacted
				ui.Checkbox(c.Key("export-unredacted"), &s.unredacted, "Export unredacted (include original values)")
				if !s.unredacted {
					ui.Checkbox(c.Key("export-headers"), &s.options.Headers, "Headers, trailers and cookies").Tooltip("Replace every header and trailer value except Content-Type and Accept; remove cookies.")
					ui.Checkbox(c.Key("export-query"), &s.options.Query, "URL query values").Tooltip("Replace all query values, including structured copies.")
					ui.Checkbox(c.Key("export-auth"), &s.options.Auth, "Authorization and URL credentials").Tooltip("Remove structured auth, URL userinfo and fragments; header values are controlled separately.")
					ui.Checkbox(c.Key("export-variables"), &s.options.Variables, "Collection, folder and environment variables").Tooltip("Replace every variable value, including disabled entries.")
					ui.Checkbox(c.Key("export-bodies"), &s.options.Bodies, "Bodies and stream messages").Tooltip("Remove request and response bodies, binary payloads and all stream messages.")
					ui.Checkbox(c.Key("export-notes"), &s.options.ScriptsNotes, "Scripts, Checks and private notes").Tooltip("Remove scripts (including exported Checks), session titles, descriptions, notes and diagnostics.")
				}
				if before != s.options || raw != s.unredacted {
					s.reviewed = false
				}
				ui.Text(c, "Field-based redaction is not secret detection. Review retained fields before sharing.").FontSize(uikit.TextBody).TextColor(t.Warning).
					Tooltip("Paths, hosts, names, parameter names, Content-Type/Accept, assertion values and unselected fields may contain secrets. Removing scripts also removes Postman Checks.")
				for _, warning := range s.warnings {
					uikit.Body(c, "• "+warning)
				}
			})
			ui.Checkbox(c.Key("export-review"), &s.reviewed, "I understand the scope and will review the exported file before sharing")
			uikit.DialogFooter(c).Children(func() {
				if uikit.SecondaryButton(c, "Cancel").Clicked() {
					s.open = false
				}
				if uikit.PrimaryButton(c, "Save export…").Disabled(!s.reviewed).Clicked() {
					job := *s
					s.open = false
					go a.writeReviewedExport(job)
				}
			})
		})
	})
}

func (a *app) writeReviewedExport(job exportReview) {
	options := job.options
	if job.unredacted {
		options = exportOptions{}
	}
	data, err := redactExport(job.data, options)
	if err != nil {
		a.setMessage(job.title + ": " + err.Error())
		return
	}
	ext := strings.TrimPrefix(filepath.Ext(job.file), ".")
	path, err := mygo.Dialog.Save(mygo.SaveDialogOptions{Title: job.title, DefaultPath: job.file,
		Filters: []mygo.FileFilter{{Name: "Export", Extensions: []string{ext}}}})
	if err != nil {
		a.setMessage(job.title + ": " + err.Error())
		return
	}
	if path == "" {
		return
	}
	if err := writePrivateFile(path, data); err != nil {
		a.setMessage(job.title + ": " + err.Error())
		return
	}
	a.setMessage("Exported to " + path)
}

const exportReplacement = "[REDACTED]"

// redactExport accepts only formats generated by this app. HAR and sessions
// reject unknown members rather than silently retaining future payload fields.
// An explicit all-off export is byte-for-byte identical, including formatting.
func redactExport(data []byte, options exportOptions) ([]byte, error) {
	if options == (exportOptions{}) {
		return bytes.Clone(data), nil
	}
	var probe struct {
		Log     jsontext.Value `json:"log"`
		Flows   jsontext.Value `json:"flows"`
		Version int            `json:"version"`
	}
	if err := json.Unmarshal(data, &probe); err != nil {
		return nil, err
	}
	var value any
	switch postman.Detect(data) {
	case postman.KindCollection, postman.KindEnvironment, postman.KindGlobals:
		var doc exportPostmanNode
		if err := json.Unmarshal(data, &doc); err != nil {
			return nil, err
		}
		doc.redact(options)
		value = doc
	default:
		switch {
		case probe.Log != nil:
			var doc harFile
			if err := json.Unmarshal(data, &doc, json.RejectUnknownMembers(true)); err != nil {
				return nil, err
			}
			redactHAR(&doc, options)
			value = doc
		case probe.Flows != nil && probe.Version == 1:
			var doc sessionFile
			if err := json.Unmarshal(data, &doc, json.RejectUnknownMembers(true)); err != nil {
				return nil, err
			}
			redactSession(&doc, options)
			value = doc
		default:
			return nil, errors.New("unsupported export format; no file was written")
		}
	}
	out, err := json.Marshal(value, jsontext.WithIndent("  "))
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}

// Postman's exported nodes share auth, variables, events and descriptions at
// collection, folder and request levels. Unchanged metadata stays verbatim;
// there is no recursive search-and-replace in arbitrary JSON or script text.
type exportPostmanNode struct {
	Info            *exportPostmanNode        `json:"info,omitempty"`
	Item            []exportPostmanNode       `json:"item,omitzero"`
	Request         *exportPostmanRequest     `json:"request,omitempty"`
	OriginalRequest *exportPostmanRequest     `json:"originalRequest,omitempty"`
	Response        []exportPostmanNode       `json:"response,omitempty"`
	Auth            jsontext.Value            `json:"auth,omitempty"`
	Event           jsontext.Value            `json:"event,omitempty"`
	Description     jsontext.Value            `json:"description,omitempty"`
	Variable        []exportPostmanValue      `json:"variable,omitempty"`
	Values          []exportPostmanValue      `json:"values,omitzero"`
	Header          []exportPostmanValue      `json:"header,omitzero"`
	Cookie          jsontext.Value            `json:"cookie,omitempty"`
	Body            jsontext.Value            `json:"body,omitempty"`
	Rest            map[string]jsontext.Value `json:",inline"`
}

type exportPostmanValue struct {
	Key   string                    `json:"key"`
	Value jsontext.Value            `json:"value"`
	Rest  map[string]jsontext.Value `json:",inline"`
}

type exportPostmanRequest struct {
	Header []exportPostmanValue      `json:"header"`
	URL    exportPostmanURL          `json:"url"`
	Auth   jsontext.Value            `json:"auth,omitempty"`
	Body   jsontext.Value            `json:"body,omitempty"`
	Rest   map[string]jsontext.Value `json:",inline"`
}

type exportPostmanURL struct {
	Raw   string                    `json:"raw"`
	Host  []string                  `json:"host,omitempty"`
	Query []exportPostmanValue      `json:"query,omitempty"`
	Hash  string                    `json:"hash,omitempty"`
	Rest  map[string]jsontext.Value `json:",inline"`
}

func (n *exportPostmanNode) redact(o exportOptions) {
	if n.Info != nil {
		n.Info.redact(o)
	}
	for i := range n.Item {
		n.Item[i].redact(o)
	}
	for i := range n.Response {
		n.Response[i].redact(o)
	}
	for _, r := range []*exportPostmanRequest{n.Request, n.OriginalRequest} {
		if r == nil {
			continue
		}
		redactPostmanHeaders(r.Header, o)
		r.URL.Raw = redactExportURL(r.URL.Raw, o)
		if o.Query {
			redactPostmanValues(r.URL.Query)
		}
		if o.Auth {
			if r.Auth != nil { // absent auth inherits, and the parents are redacted too
				r.Auth = jsontext.Value(`{"type":"noauth"}`)
			}
			r.URL.Hash = ""
			// writeURL also places userinfo in its structured host parts.
			host := strings.Join(r.URL.Host, ".")
			if _, tail, ok := strings.CutLast(host, "@"); ok {
				r.URL.Host = strings.Split(tail, ".")
			}
		}
		if o.Bodies {
			r.Body = nil
		}
	}
	if o.Auth && n.Auth != nil {
		n.Auth = jsontext.Value(`{"type":"noauth"}`)
	}
	if o.Variables {
		redactPostmanValues(n.Variable)
		redactPostmanValues(n.Values)
	}
	redactPostmanHeaders(n.Header, o)
	if o.Headers {
		n.Cookie = nil
	}
	if o.Bodies {
		n.Body = nil
	}
	if o.ScriptsNotes {
		n.Event, n.Description = nil, nil
	}
}

func redactPostmanValues(values []exportPostmanValue) {
	for i := range values {
		values[i].Value = jsontext.Value(`"` + exportReplacement + `"`)
	}
}

func redactPostmanHeaders(values []exportPostmanValue, o exportOptions) {
	if !o.Headers {
		return
	}
	for i := range values {
		if !exportPublicHeader(values[i].Key) {
			values[i].Value = jsontext.Value(`"` + exportReplacement + `"`)
		}
	}
}

func exportPublicHeader(name string) bool {
	return strings.EqualFold(name, "Content-Type") || strings.EqualFold(name, "Accept")
}

// Work on the URL's syntactic fields, preserving raw paths and {{templates}}.
// Parsing via net/url would reject templated authorities or escape braces.
func redactExportURL(raw string, o exportOptions) string {
	base, fragment, hasFragment := strings.Cut(raw, "#")
	base, query, hasQuery := strings.Cut(base, "?")
	if o.Auth {
		prefix, authority := "", base
		if scheme, rest, ok := strings.Cut(base, "://"); ok {
			prefix, authority = scheme+"://", rest
		}
		host, path, slash := strings.Cut(authority, "/")
		if _, tail, ok := strings.CutLast(host, "@"); ok {
			host = tail
		}
		base = prefix + host
		if slash {
			base += "/" + path
		}
		hasFragment = false
	}
	if hasQuery {
		if o.Query && query != "" {
			var parts []string
			for part := range strings.SplitSeq(query, "&") {
				key, _, _ := strings.Cut(part, "=")
				parts = append(parts, key+"=REDACTED")
			}
			query = strings.Join(parts, "&")
		}
		base += "?" + query
	}
	if hasFragment {
		base += "#" + fragment
	}
	return base
}

func redactHAR(doc *harFile, o exportOptions) {
	for i := range doc.Log.Entries {
		e := &doc.Log.Entries[i]
		e.Request.URL = redactExportURL(e.Request.URL, o)
		e.Response.RedirectURL = redactExportURL(e.Response.RedirectURL, o)
		if o.Query {
			for j := range e.Request.QueryString {
				e.Request.QueryString[j].Value = exportReplacement
			}
		}
		if o.Headers {
			for _, headers := range [][]harNameValue{e.Request.Headers, e.Response.Headers} {
				for j := range headers {
					if !exportPublicHeader(headers[j].Name) {
						headers[j].Value = exportReplacement
					}
				}
			}
			e.Request.Cookies, e.Response.Cookies = nil, nil
		}
		if o.Bodies {
			e.Request.PostData = nil
			e.Response.Content.Text, e.Response.Content.Encoding = "", ""
		}
	}
}

func redactSession(doc *sessionFile, o exportOptions) {
	if o.ScriptsNotes {
		doc.Title, doc.Notes = "", ""
	}
	for i := range doc.Flows {
		f := &doc.Flows[i]
		f.URL, f.Path = redactExportURL(f.URL, o), redactExportURL(f.Path, o)
		if o.Auth {
			f.Host = redactExportURL(f.Host, o)
		}
		f.ReqHeaders = redactExportHeaderBlock(f.ReqHeaders, o)
		f.ResHeaders = redactExportHeaderBlock(f.ResHeaders, o)
		if o.Headers {
			for _, headers := range []http.Header{f.ReqHeader, f.RespHeader, f.ReqTrailer, f.ResTrailer} {
				for name, values := range headers {
					if !exportPublicHeader(name) {
						for j := range values {
							values[j] = exportReplacement
						}
					}
				}
			}
		}
		if o.Bodies {
			f.ReqBody, f.ResBody = "", ""
			f.ReqBytes, f.ResBytes = nil, nil
		}
		if o.ScriptsNotes {
			f.Note, f.ConnectionLog, f.ConnectionError, f.ReqError, f.ResError = "", "", "", "", ""
			f.Actions, f.DebugKey, f.DebugRun = nil, "", ""
		}
	}
	if o.Bodies {
		// Includes text previews, binary payloads, SSE event IDs and names.
		doc.Frames = nil
	}
}

func redactExportHeaderBlock(block string, o exportOptions) string {
	if !o.Headers && !o.Query && !o.Auth {
		return block
	}
	var lines []string
	for i, line := range strings.Split(strings.ReplaceAll(block, "\r\n", "\n"), "\n") {
		if i == 0 {
			parts := strings.Fields(line)
			if len(parts) == 3 && strings.HasPrefix(parts[2], "HTTP/") {
				lines = append(lines, parts[0]+" "+redactExportURL(parts[1], o)+" "+parts[2])
				continue
			}
			if strings.HasPrefix(line, "HTTP/") {
				lines = append(lines, line)
				continue
			}
		}
		if !o.Headers {
			lines = append(lines, line)
			continue
		}
		name, _, ok := strings.Cut(line, ":")
		if !ok || strings.TrimSpace(name) != name || name == "" {
			continue // Never retain folded or malformed header payloads.
		}
		if exportPublicHeader(name) {
			lines = append(lines, line)
		} else {
			lines = append(lines, name+": "+exportReplacement)
		}
	}
	return strings.Join(lines, "\n")
}
