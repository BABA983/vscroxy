// Package clientsetup points one client at the capture proxy without changing
// system-wide settings: a terminal, a browser with its own temporary profile,
// an Android emulator through adb, an iOS simulator, a Java truststore or an
// Electron app. Everything a caller can review is built here as data; only the
// platform launchers and the explicit adb/keytool/simctl steps run commands.
package clientsetup

import (
	"errors"
	"fmt"
	"net"
	"strconv"
	"strings"
)

// Proxy is the capture listener and the public CA a client should use.
type Proxy struct {
	// Addr is the listener's host:port, as the app displays it.
	Addr string
	// CAPath is the public CA certificate in PEM form. It never holds the
	// signing key.
	CAPath string
}

// URL is the proxy as an HTTP proxy URL.
func (p Proxy) URL() string { return "http://" + p.Addr }

// HostPort splits Addr and rejects a port no proxy could listen on.
func (p Proxy) HostPort() (string, int, error) {
	host, port, err := net.SplitHostPort(p.Addr)
	if err != nil {
		return "", 0, fmt.Errorf("proxy address %q: %w", p.Addr, err)
	}
	n, err := strconv.Atoi(port)
	if err != nil || n < 1 || n > 65535 {
		return "", 0, fmt.Errorf("proxy address %q has no usable port", p.Addr)
	}
	return host, n, nil
}

// NoProxy keeps loopback traffic away from the proxy. A client that connected
// to the proxy through the proxy would loop; the capture app's own listener is
// always loopback.
const NoProxy = "localhost,127.0.0.1,::1"

// Environment is the process environment that points common HTTP clients at
// the proxy and the public CA. Both cases are set because curl, Python, Node
// and Go disagree about which one wins.
func Environment(p Proxy) ([]string, error) {
	if _, _, err := p.HostPort(); err != nil {
		return nil, err
	}
	if strings.TrimSpace(p.CAPath) == "" {
		return nil, errors.New("CA path is empty")
	}
	proxy := p.URL()
	return []string{
		"HTTP_PROXY=" + proxy,
		"HTTPS_PROXY=" + proxy,
		"ALL_PROXY=" + proxy,
		"http_proxy=" + proxy,
		"https_proxy=" + proxy,
		"all_proxy=" + proxy,
		"NO_PROXY=" + NoProxy,
		"no_proxy=" + NoProxy,
		"NODE_EXTRA_CA_CERTS=" + p.CAPath,
		"REQUESTS_CA_BUNDLE=" + p.CAPath,
		"SSL_CERT_FILE=" + p.CAPath,
		"CURL_CA_BUNDLE=" + p.CAPath,
		"GIT_SSL_CAINFO=" + p.CAPath,
		"PIP_CERT=" + p.CAPath,
		"DENO_CERT=" + p.CAPath,
	}, nil
}

// POSIXScript is a shell script that exports the environment for its own
// window and then replaces itself with the user's login shell. It changes
// nothing outside that process tree.
func POSIXScript(p Proxy) (string, error) {
	env, err := Environment(p)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# Generated by vscroxy for this window only. No system settings change.\n")
	for _, entry := range env {
		name, value, _ := strings.Cut(entry, "=")
		fmt.Fprintf(&b, "export %s=%s\n", name, POSIXQuote(value))
	}
	b.WriteString("exec \"${SHELL:-/bin/sh}\" -l\n")
	return b.String(), nil
}

// WindowsScript is the batch equivalent of POSIXScript. It is run by a new
// cmd.exe window, so the variables live only in that window.
func WindowsScript(p Proxy) (string, error) {
	env, err := Environment(p)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("@echo off\r\n")
	b.WriteString("rem Generated by vscroxy for this window only. No system settings change.\r\n")
	for _, entry := range env {
		name, value, _ := strings.Cut(entry, "=")
		fmt.Fprintf(&b, "set \"%s=%s\"\r\n", name, windowsBatchValue(value))
	}
	return b.String(), nil
}

// windowsBatchValue keeps a percent sign literal in a batch file; cmd expands
// %NAME% even inside quotes.
func windowsBatchValue(s string) string { return strings.ReplaceAll(s, "%", "%%") }

// POSIXQuote quotes one word for a POSIX shell. The result is safe to paste
// into sh, bash or zsh, including paths with spaces and apostrophes.
func POSIXQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// POSIXCommandLine renders a command for review and copying.
func POSIXCommandLine(name string, args []string) string {
	words := make([]string, 0, len(args)+1)
	words = append(words, posixWord(name))
	for _, arg := range args {
		words = append(words, posixWord(arg))
	}
	return strings.Join(words, " ")
}

func posixWord(s string) string {
	if s != "" && strings.IndexFunc(s, func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' ||
			strings.ContainsRune("-_.:/@%+=,", r))
	}) < 0 {
		return s
	}
	return POSIXQuote(s)
}

// WindowsQuote quotes one argument for cmd.exe. Windows paths cannot contain a
// double quote, so wrapping is enough; a percent sign is doubled because cmd
// expands it even inside quotes.
func WindowsQuote(s string) string {
	return `"` + strings.ReplaceAll(s, "%", "%%") + `"`
}

// WindowsCommandLine renders a command for review and copying.
func WindowsCommandLine(name string, args []string) string {
	words := make([]string, 0, len(args)+1)
	words = append(words, WindowsQuote(name))
	for _, arg := range args {
		words = append(words, WindowsQuote(arg))
	}
	return strings.Join(words, " ")
}

// WindowsStartLine opens script in a new console window that stays open after
// the script finishes. The empty title keeps start from treating a quoted path
// as its window title.
func WindowsStartLine(script string) string {
	return `start "" cmd.exe /k ` + WindowsQuote(script)
}

// ChromeArgs starts Chrome or Chromium with a separate profile and the capture
// proxy. Certificate trust is not bypassed: the browser uses the system trust
// store on macOS and Windows, and NSS on Linux.
func ChromeArgs(p Proxy, profile string) ([]string, error) {
	if _, _, err := p.HostPort(); err != nil {
		return nil, err
	}
	if strings.TrimSpace(profile) == "" {
		return nil, errors.New("Chrome profile directory is empty")
	}
	return []string{
		"--user-data-dir=" + profile,
		"--proxy-server=" + p.URL(),
		"--proxy-bypass-list=localhost;127.0.0.1;::1",
		"--no-first-run",
		"--no-default-browser-check",
		"--new-window",
		"about:blank",
	}, nil
}

// FirefoxUserJS writes the proxy settings into a temporary profile's user.js.
// The profile never touches the user's main Firefox profile.
func FirefoxUserJS(p Proxy) (string, error) {
	host, port, err := p.HostPort()
	if err != nil {
		return "", err
	}
	return fmt.Sprintf(`// Generated by vscroxy for a temporary profile. No system settings change.
user_pref("network.proxy.type", 1);
user_pref("network.proxy.http", %q);
user_pref("network.proxy.http_port", %d);
user_pref("network.proxy.ssl", %q);
user_pref("network.proxy.ssl_port", %d);
user_pref("network.proxy.share_proxy_settings", false);
user_pref("network.proxy.no_proxies_on", %q);
user_pref("network.proxy.allow_hijacking_localhost", true);
user_pref("security.enterprise_roots.enabled", true);
user_pref("browser.shell.checkDefaultBrowser", false);
user_pref("browser.startup.page", 0);
user_pref("browser.startup.homepage", "about:blank");
user_pref("toolkit.telemetry.reportingpolicy.firstRun", false);
`, host, port, host, port, NoProxy), nil
}

// FirefoxArgs starts a separate Firefox instance on the temporary profile.
func FirefoxArgs(profile string) ([]string, error) {
	if strings.TrimSpace(profile) == "" {
		return nil, errors.New("Firefox profile directory is empty")
	}
	return []string{"-profile", profile, "-no-remote"}, nil
}

// ElectronArgs points an Electron app's Chromium layer at the proxy. It never
// disables certificate verification.
func ElectronArgs(p Proxy) ([]string, error) {
	if _, _, err := p.HostPort(); err != nil {
		return nil, err
	}
	return []string{
		"--proxy-server=" + p.URL(),
		"--proxy-bypass-list=localhost;127.0.0.1;::1",
	}, nil
}

// KeytoolArgs imports the public CA into a PKCS#12 truststore. The caller owns
// the truststore path; this package never writes a JDK installation.
func KeytoolArgs(p Proxy, keystore string) ([]string, error) {
	if strings.TrimSpace(p.CAPath) == "" {
		return nil, errors.New("CA path is empty")
	}
	if strings.TrimSpace(keystore) == "" {
		return nil, errors.New("Java truststore path is empty")
	}
	return []string{
		"-importcert", "-noprompt",
		"-alias", "vscroxy-ca",
		"-file", p.CAPath,
		"-keystore", keystore,
		"-storetype", "PKCS12",
		"-storepass", "changeit",
	}, nil
}

// JVMArgs makes a JVM use the truststore this package writes.
func JVMArgs(keystore string) []string {
	return []string{
		"-Djavax.net.ssl.trustStore=" + keystore,
		"-Djavax.net.ssl.trustStorePassword=changeit",
	}
}
