// Command third-party-notices writes the Go module section of
// THIRD_PARTY_NOTICES.md from the modules the shipped binaries link, and the
// license file each module ships. Run it from the repository root:
//
//	go run ./scripts/third-party-notices          # rewrite the file
//	go run ./scripts/third-party-notices -check   # fail when it is out of date
//
// CI runs -check, so a module added to go.mod or a dependency cannot ship
// without its license.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

const (
	beginMarker = "<!-- BEGIN GENERATED: Go modules (scripts/third-party-notices) -->"
	endMarker   = "<!-- END GENERATED: Go modules -->"
	noticesFile = "THIRD_PARTY_NOTICES.md"
)

// binaries are the commands whose linked modules the notices must cover.
var binaries = []string{"./cmd/vscroxy", "./cmd/vscroxy-cli", "./cmd/vscroxy-mcp"}

type module struct {
	Path    string
	Version string
	Dir     string
	// Note says where a replaced module's code comes from.
	Note string
}

type listedPackage struct {
	Module *struct {
		Path    string
		Version string
		Dir     string
		Main    bool
		Replace *struct {
			Path    string
			Version string
			Dir     string
		}
	}
}

func main() {
	check := flag.Bool("check", false, "fail when THIRD_PARTY_NOTICES.md is out of date instead of rewriting it")
	flag.Parse()

	block, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "third-party-notices:", err)
		os.Exit(1)
	}
	old, err := os.ReadFile(noticesFile)
	if err != nil {
		fmt.Fprintln(os.Stderr, "third-party-notices:", err)
		os.Exit(1)
	}
	updated, err := replaceBlock(old, block)
	if err != nil {
		fmt.Fprintln(os.Stderr, "third-party-notices:", err)
		os.Exit(1)
	}
	if *check {
		if !bytes.Equal(old, updated) {
			fmt.Fprintf(os.Stderr, "%s is out of date; run go run ./scripts/third-party-notices\n", noticesFile)
			os.Exit(1)
		}
		return
	}
	if bytes.Equal(old, updated) {
		return
	}
	if err := os.WriteFile(noticesFile, updated, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "third-party-notices:", err)
		os.Exit(1)
	}
}

// generate lists the modules the binaries link and writes a section for each.
func generate() ([]byte, error) {
	modules, err := linkedModules()
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "## Go modules")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "`vscroxy`, `vscroxy-cli` and `vscroxy-mcp` link these modules. Each")
	fmt.Fprintln(&out, "section reproduces the license files the module's authors ship. The list")
	fmt.Fprintln(&out, "and the texts are generated by `scripts/third-party-notices` from")
	fmt.Fprintln(&out, "`go list -deps`; CI fails when this section is out of date.")
	for _, m := range modules {
		licenses, err := licenseFiles(m.Dir)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", m.Path, err)
		}
		if len(licenses) == 0 {
			return nil, fmt.Errorf("%s %s: no LICENSE, COPYING or NOTICE file", m.Path, m.Version)
		}
		fmt.Fprintln(&out)
		fmt.Fprintf(&out, "### %s", m.Path)
		if m.Version != "" {
			fmt.Fprintf(&out, " %s", m.Version)
		}
		if m.Note != "" {
			fmt.Fprintf(&out, " (%s)", m.Note)
		}
		fmt.Fprintln(&out)
		for _, name := range licenses {
			text, err := os.ReadFile(filepath.Join(m.Dir, name))
			if err != nil {
				return nil, err
			}
			fmt.Fprintln(&out)
			fmt.Fprintf(&out, "`%s`:\n\n", name)
			fmt.Fprintln(&out, "````")
			out.Write(bytes.TrimRight(text, " \t\r\n"))
			fmt.Fprintln(&out)
			fmt.Fprintln(&out, "````")
		}
	}
	fmt.Fprintln(&out)
	return out.Bytes(), nil
}

// linkedModules returns every third-party module linked into the binaries,
// once, sorted by path.
func linkedModules() ([]module, error) {
	args := append([]string{"list", "-deps", "-json"}, binaries...)
	cmd := exec.Command("go", args...)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	data, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %v: %s", err, stderr.String())
	}
	seen := map[string]module{}
	dec := json.NewDecoder(bytes.NewReader(data))
	for dec.More() {
		var p listedPackage
		if err := dec.Decode(&p); err != nil {
			return nil, err
		}
		if p.Module == nil || p.Module.Main {
			continue
		}
		m := module{Path: p.Module.Path, Version: p.Module.Version, Dir: p.Module.Dir}
		if r := p.Module.Replace; r != nil {
			if r.Dir != "" {
				m.Dir = r.Dir
			}
			if r.Path != "" && r.Path != p.Module.Path {
				if strings.HasPrefix(r.Path, ".") || filepath.IsAbs(r.Path) {
					m.Note = "patched in " + r.Path
				} else {
					m.Path = p.Module.Path + " → " + r.Path
					if r.Version != "" {
						m.Version = r.Version
					}
				}
			}
		}
		if m.Dir == "" {
			return nil, fmt.Errorf("%s: no module directory; run go mod download", m.Path)
		}
		seen[m.Path+"@"+m.Version] = m
	}
	modules := make([]module, 0, len(seen))
	for _, m := range seen {
		modules = append(modules, m)
	}
	slices.SortFunc(modules, func(a, b module) int { return strings.Compare(a.Path, b.Path) })
	return modules, nil
}

// licenseFiles are the license files at the module's root, in a stable order.
func licenseFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		upper := strings.ToUpper(e.Name())
		if strings.HasPrefix(upper, "LICENSE") || strings.HasPrefix(upper, "COPYING") || strings.HasPrefix(upper, "NOTICE") {
			names = append(names, e.Name())
		}
	}
	slices.Sort(names)
	return names, nil
}

// replaceBlock puts block between the markers, keeping everything else.
func replaceBlock(file, block []byte) ([]byte, error) {
	start := bytes.Index(file, []byte(beginMarker))
	if start < 0 {
		return nil, fmt.Errorf("%s has no %q marker", noticesFile, beginMarker)
	}
	end := bytes.Index(file[start:], []byte(endMarker))
	if end < 0 {
		return nil, fmt.Errorf("%s has no %q marker", noticesFile, endMarker)
	}
	end += start
	var out bytes.Buffer
	out.Write(file[:start])
	out.WriteString(beginMarker)
	out.WriteString("\n")
	out.Write(block)
	out.Write(file[end:])
	return out.Bytes(), nil
}
